<?php
declare(strict_types=1);
/**
 * School ERP - Installation wizard.
 * Creates the database & tables, seeds defaults and the Super Admin, then writes config/config.php.
 * Once installed it locks itself (delete config/config.php to reinstall).
 */
define('BASE_PATH', dirname(__DIR__));
define('APP_PATH', BASE_PATH . '/app');
define('UPLOAD_PATH', BASE_PATH . '/uploads');
define('STORAGE_PATH', BASE_PATH . '/storage');

require APP_PATH . '/core/DB.php';
require APP_PATH . '/core/helpers.php';
require APP_PATH . '/core/Auth.php';
require APP_PATH . '/core/services.php';
require APP_PATH . '/seed.php';

session_name('SCHOOLERP_INSTALL');
session_start();
header('X-Frame-Options: DENY');
header('X-Content-Type-Options: nosniff');

$configFile = BASE_PATH . '/config/config.php';
$installed = is_file($configFile);
$errors = [];
$done = false;

$req = [
    'PHP 8.1 or newer' => version_compare(PHP_VERSION, '8.1.0', '>='),
    'PDO MySQL extension' => extension_loaded('pdo_mysql'),
    'mbstring extension' => extension_loaded('mbstring'),
    'fileinfo extension' => extension_loaded('fileinfo'),
    'config/ is writable' => is_writable(BASE_PATH . '/config'),
    'uploads/ is writable' => is_writable(BASE_PATH . '/uploads'),
    'storage/ is writable' => is_writable(BASE_PATH . '/storage') && is_writable(BASE_PATH . '/storage/logs') && is_writable(BASE_PATH . '/storage/backups'),
];
$reqOk = !in_array(false, $req, true);

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!hash_equals(csrf_token(), (string)($_POST['_token'] ?? ''))) {
        $errors[] = 'Security token expired. Please retry.';
    }
    $in = array_map(fn($v) => is_string($v) ? trim($v) : $v, $_POST);
    $errors = array_merge($errors, array_values(validate($in, [
        'db_host' => 'required|max:100', 'db_port' => 'required|integer', 'db_name' => 'required|max:64', 'db_user' => 'required|max:64',
        'school_name' => 'required|max:150', 'admin_name' => 'required|max:120', 'admin_username' => 'required|min:4|max:60',
        'admin_email' => 'required|email', 'admin_password' => 'required|min:8|confirmed',
    ], ['admin_password' => 'Admin password'])));
    if (!preg_match('/^[A-Za-z0-9_]+$/', $in['db_name'] ?? '')) {
        $errors[] = 'Database name may only contain letters, numbers and underscores.';
    }
    $pw = (string)($in['admin_password'] ?? '');
    if ($pw && (!preg_match('/[A-Z]/', $pw) || !preg_match('/[a-z]/', $pw) || !preg_match('/\d/', $pw))) {
        $errors[] = 'Admin password must contain upper-case, lower-case letters and a number.';
    }
    if (!$errors && !$reqOk) {
        $errors[] = 'Please fix the server requirements first.';
    }
    if (!$errors) {
        try {
            $db = ['host' => $in['db_host'], 'port' => (int)$in['db_port'], 'name' => $in['db_name'], 'user' => $in['db_user'], 'pass' => (string)($_POST['db_pass'] ?? '')];
            $pdo = new PDO("mysql:host={$db['host']};port={$db['port']};charset=utf8mb4", $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$db['name']}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
            date_default_timezone_set($in['timezone'] ?: 'Asia/Karachi');
            DB::connect($db);
            $sql = file_get_contents(BASE_PATH . '/database/schema.sql');
            $sql = preg_replace('/^--.*$/m', '', $sql);
            foreach (preg_split('/;\s*(\r?\n|$)/', $sql) as $stmt) {
                if (trim($stmt) !== '') {
                    DB::pdo()->exec($stmt);
                }
            }
            if ((int)DB::val('SELECT COUNT(*) FROM users') > 0) {
                throw new RuntimeException('The selected database already contains users. Use an empty database or remove the existing tables.');
            }
            seed_base(['name' => $in['school_name'], 'address' => $in['school_address'] ?? '', 'phone' => $in['school_phone'] ?? '', 'email' => $in['admin_email']]);
            $roleId = (int)DB::val("SELECT id FROM roles WHERE slug='super_admin'");
            DB::insert('users', [
                'role_id' => $roleId, 'name' => $in['admin_name'], 'username' => $in['admin_username'], 'email' => $in['admin_email'],
                'password' => password_hash($pw, PASSWORD_DEFAULT), 'status' => 'active', 'password_changed_at' => date('Y-m-d H:i:s'),
            ]);
            if (!empty($in['demo'])) {
                require BASE_PATH . '/database/demo_seed.php';
                run_demo_seed();
            }
            $config = "<?php\n// Generated by installer on " . date('Y-m-d H:i:s') . "\nreturn " . var_export([
                'db' => $db,
                'timezone' => $in['timezone'] ?: 'Asia/Karachi',
                'debug' => false,
                'app_key' => bin2hex(random_bytes(32)),
            ], true) . ";\n";
            if (file_put_contents($configFile, $config, LOCK_EX) === false) {
                throw new RuntimeException('Could not write config/config.php');
            }
            @chmod($configFile, 0640);
            $done = true;
            session_destroy();
        } catch (Throwable $e) {
            $errors[] = 'Installation failed: ' . $e->getMessage();
        }
    }
}
$v = fn($k, $d = '') => e($_POST[$k] ?? $d);
?><!doctype html>
<html lang="en">
<head>
    <meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
    <title>Install School ERP</title>
    <link rel="stylesheet" href="../assets/vendor/bootstrap/css/bootstrap.min.css">
    <link rel="stylesheet" href="../assets/vendor/icons/bootstrap-icons.min.css">
    <link rel="stylesheet" href="../assets/css/app.css">
</head>
<body style="background:linear-gradient(140deg,#0f2a6b,#1d4ed8 60%,#3b82f6)">
<div class="container py-5" style="max-width:860px">
    <div class="text-center text-white mb-4">
        <div class="display-6 fw-bold"><i class="bi bi-mortarboard-fill"></i> School ERP</div>
        <div class="opacity-75">Installation Wizard</div>
    </div>
    <div class="card shadow-lg"><div class="card-body p-4">
    <?php if ($installed && !$done): ?>
        <div class="text-center py-4">
            <i class="bi bi-shield-lock text-primary" style="font-size:3rem"></i>
            <h4 class="mt-3">Already installed</h4>
            <p class="text-muted">The installer is locked. To reinstall, delete <code>config/config.php</code> first.</p>
            <a href="../index.php" class="btn btn-primary">Go to login</a>
        </div>
    <?php elseif ($done): ?>
        <div class="text-center py-4">
            <i class="bi bi-check-circle-fill text-success" style="font-size:3rem"></i>
            <h4 class="mt-3">Installation complete!</h4>
            <p class="text-muted">Log in with the Super Admin account you created. For security, you may delete or protect the <code>install/</code> folder.</p>
            <a href="../index.php" class="btn btn-primary btn-lg">Open the application</a>
        </div>
    <?php else: ?>
        <h5 class="mb-3">1. Server requirements</h5>
        <div class="row g-2 mb-4">
            <?php foreach ($req as $label => $ok): ?>
                <div class="col-md-6"><i class="bi <?= $ok ? 'bi-check-circle-fill text-success' : 'bi-x-circle-fill text-danger' ?>"></i> <?= e($label) ?></div>
            <?php endforeach; ?>
        </div>
        <?php if ($errors): ?><div class="alert alert-danger"><ul class="mb-0"><?php foreach ($errors as $er): ?><li><?= e($er) ?></li><?php endforeach; ?></ul></div><?php endif; ?>
        <form method="post" autocomplete="off">
            <input type="hidden" name="_token" value="<?= e(csrf_token()) ?>">
            <h5 class="mb-3">2. Database</h5>
            <div class="row g-3 mb-4">
                <div class="col-md-5"><label class="form-label">Host</label><input name="db_host" class="form-control" value="<?= $v('db_host', 'localhost') ?>" required></div>
                <div class="col-md-2"><label class="form-label">Port</label><input name="db_port" class="form-control" value="<?= $v('db_port', '3306') ?>" required></div>
                <div class="col-md-5"><label class="form-label">Database name</label><input name="db_name" class="form-control" value="<?= $v('db_name', 'school_erp') ?>" required><div class="form-text">Created automatically if it does not exist.</div></div>
                <div class="col-md-6"><label class="form-label">Username</label><input name="db_user" class="form-control" value="<?= $v('db_user', 'root') ?>" required></div>
                <div class="col-md-6"><label class="form-label">Password</label><input type="password" name="db_pass" class="form-control"></div>
            </div>
            <h5 class="mb-3">3. School</h5>
            <div class="row g-3 mb-4">
                <div class="col-md-6"><label class="form-label">School name</label><input name="school_name" class="form-control" value="<?= $v('school_name') ?>" required></div>
                <div class="col-md-6"><label class="form-label">Phone</label><input name="school_phone" class="form-control" value="<?= $v('school_phone') ?>"></div>
                <div class="col-md-8"><label class="form-label">Address</label><input name="school_address" class="form-control" value="<?= $v('school_address') ?>"></div>
                <div class="col-md-4"><label class="form-label">Timezone</label><input name="timezone" class="form-control" value="<?= $v('timezone', 'Asia/Karachi') ?>"></div>
            </div>
            <h5 class="mb-3">4. Super Admin account</h5>
            <div class="row g-3 mb-4">
                <div class="col-md-6"><label class="form-label">Full name</label><input name="admin_name" class="form-control" value="<?= $v('admin_name') ?>" required></div>
                <div class="col-md-6"><label class="form-label">Username</label><input name="admin_username" class="form-control" value="<?= $v('admin_username', 'admin') ?>" required></div>
                <div class="col-md-12"><label class="form-label">Email</label><input type="email" name="admin_email" class="form-control" value="<?= $v('admin_email') ?>" required></div>
                <div class="col-md-6"><label class="form-label">Password</label><input type="password" name="admin_password" class="form-control" minlength="8" required><div class="form-text">Min 8 chars incl. upper, lower case and a number.</div></div>
                <div class="col-md-6"><label class="form-label">Confirm password</label><input type="password" name="admin_password_confirmation" class="form-control" required></div>
            </div>
            <div class="form-check mb-4">
                <input class="form-check-input" type="checkbox" name="demo" value="1" id="demo" <?= !empty($_POST['demo']) ? 'checked' : '' ?>>
                <label class="form-check-label" for="demo">Load sample data (classes, teachers, students, fees, exams) for evaluation. Leave unchecked for a clean production install.</label>
            </div>
            <button class="btn btn-primary btn-lg w-100" <?= $reqOk ? '' : 'disabled' ?>><i class="bi bi-rocket-takeoff"></i> Install now</button>
        </form>
    <?php endif; ?>
    </div></div>
</div>
</body>
</html>
